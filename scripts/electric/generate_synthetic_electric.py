"""Generate new electric-like graph benchmarks with pandapower.

These datasets are not modified SimBench grids. They are controlled synthetic
electric networks with water-like spatial structure: compact districts, local
connections, a few bridges, and optional loops. Time series are generated by
running pandapower power flow at each timestep.

The output keeps the existing training contract:

  pressure := voltage_pu
  demand   := net_p_mw = p_load_mw - p_sgen_mw

Ground-truth edges are saved only for post-hoc metrics.
"""

from __future__ import annotations

import argparse
import json
from pathlib import Path

import numpy as np

try:
    import pandapower as pp
except ImportError as exc:  # pragma: no cover
    raise SystemExit("This generator requires pandapower. Install with: pip install pandapower") from exc


PROJECT_ROOT = Path(__file__).resolve().parents[2]

PRESETS = {
    "electric_synth_branch": {
        "num_nodes": 52,
        "districts": 5,
        "loops_per_district": 2,
        "bridge_edges": 4,
        "extra_cross_links": 3,
        "seed": 4101,
    },
    "electric_synth_mesh": {
        "num_nodes": 52,
        "districts": 5,
        "loops_per_district": 3,
        "bridge_edges": 6,
        "extra_cross_links": 8,
        "seed": 4102,
    },
}


def canonical(u: int, v: int) -> tuple[int, int]:
    return (u, v) if u < v else (v, u)


def pairwise_dist(xy: np.ndarray) -> np.ndarray:
    diff = xy[:, None, :] - xy[None, :, :]
    return np.sqrt((diff * diff).sum(axis=-1))


def to_edge_index(edges: set[tuple[int, int]], bidirectional: bool = True) -> np.ndarray:
    rows = []
    for u, v in sorted(edges):
        rows.append((u, v))
        if bidirectional:
            rows.append((v, u))
    return np.asarray(rows, dtype=np.int64).T if rows else np.zeros((2, 0), dtype=np.int64)


def build_mst_edges(dist: np.ndarray) -> set[tuple[int, int]]:
    n = dist.shape[0]
    selected = np.zeros(n, dtype=bool)
    selected[0] = True
    edges: set[tuple[int, int]] = set()
    for _ in range(n - 1):
        best = None
        best_dist = np.inf
        for u in np.where(selected)[0]:
            candidates = np.where(~selected)[0]
            if candidates.size == 0:
                break
            v = int(candidates[np.argmin(dist[u, candidates])])
            if dist[u, v] < best_dist:
                best = (int(u), v)
                best_dist = float(dist[u, v])
        if best is None:
            break
        edges.add(canonical(*best))
        selected[best[1]] = True
    return edges


def sample_district_positions(n: int, districts: int, rng: np.random.Generator) -> tuple[np.ndarray, np.ndarray]:
    labels = np.arange(n) % int(districts)
    rng.shuffle(labels)
    angles = np.linspace(0.0, 2.0 * np.pi, int(districts), endpoint=False)
    angles += rng.normal(0.0, 0.16, size=int(districts))
    radii = rng.uniform(0.22, 0.34, size=int(districts))
    centers = np.column_stack([0.5 + radii * np.cos(angles), 0.5 + radii * np.sin(angles)])
    xy = np.zeros((n, 2), dtype=np.float32)
    for i in range(n):
        xy[i] = centers[labels[i]] + rng.normal(0.0, 0.055, size=2)
    return np.clip(xy, 0.03, 0.97).astype(np.float32), labels.astype(np.int64)


def build_water_like_electric_edges(
    xy: np.ndarray,
    labels: np.ndarray,
    rng: np.random.Generator,
    loops_per_district: int,
    bridge_edges: int,
    extra_cross_links: int,
) -> set[tuple[int, int]]:
    dist = pairwise_dist(xy)
    edges: set[tuple[int, int]] = set()
    representatives: list[int] = []

    for label in np.unique(labels):
        nodes = np.where(labels == label)[0].astype(int)
        local_dist = pairwise_dist(xy[nodes])
        for u_local, v_local in build_mst_edges(local_dist):
            edges.add(canonical(int(nodes[u_local]), int(nodes[v_local])))

        centroid = xy[nodes].mean(axis=0, keepdims=True)
        representatives.append(int(nodes[np.argmin(np.linalg.norm(xy[nodes] - centroid, axis=1))]))

        local_candidates = []
        for i, u in enumerate(nodes):
            for v in nodes[i + 1 :]:
                edge = canonical(int(u), int(v))
                if edge not in edges:
                    local_candidates.append((float(dist[u, v]), edge))
        local_candidates.sort(key=lambda item: item[0])
        pool = local_candidates[: max(loops_per_district * 8, loops_per_district)]
        rng.shuffle(pool)
        for _, edge in pool[: max(0, loops_per_district)]:
            edges.add(edge)

    rep_dist = dist[np.ix_(representatives, representatives)]
    for u_local, v_local in build_mst_edges(rep_dist):
        edges.add(canonical(representatives[u_local], representatives[v_local]))

    cross_candidates = []
    for u in range(len(xy)):
        for v in range(u + 1, len(xy)):
            if labels[u] == labels[v]:
                continue
            edge = (u, v)
            if edge not in edges:
                cross_candidates.append((float(dist[u, v]), edge))
    cross_candidates.sort(key=lambda item: item[0])
    pool = cross_candidates[: max((bridge_edges + extra_cross_links) * 8, 1)]
    rng.shuffle(pool)
    for _, edge in pool[: max(0, bridge_edges + extra_cross_links)]:
        edges.add(edge)
    return edges


def build_knn_edges(xy: np.ndarray, k: int) -> set[tuple[int, int]]:
    dist = pairwise_dist(xy)
    np.fill_diagonal(dist, np.inf)
    idx = np.argsort(dist, axis=1)[:, : min(k, xy.shape[0] - 1)]
    edges = set()
    for u in range(xy.shape[0]):
        for v in idx[u]:
            edges.add(canonical(int(u), int(v)))
    return edges


def create_power_net(xy: np.ndarray, edges: set[tuple[int, int]], rng: np.random.Generator):
    net = pp.create_empty_network()
    buses = [pp.create_bus(net, vn_kv=0.4, name=f"B{i:03d}") for i in range(len(xy))]
    source = int(np.argmin(np.linalg.norm(xy - np.array([[0.5, 0.5]], dtype=np.float32), axis=1)))
    pp.create_ext_grid(net, bus=buses[source], vm_pu=1.025)
    dist = pairwise_dist(xy)

    for u, v in sorted(edges):
        length_km = float(np.clip(0.010 + 0.14 * dist[u, v], 0.006, 0.12))
        cable_scale = float(rng.uniform(0.85, 1.20))
        pp.create_line_from_parameters(
            net,
            from_bus=buses[u],
            to_bus=buses[v],
            length_km=length_km,
            r_ohm_per_km=0.16 * cable_scale,
            x_ohm_per_km=0.055 * cable_scale,
            c_nf_per_km=210.0,
            max_i_ka=0.35,
            name=f"L{u:03d}_{v:03d}",
            in_service=True,
        )

    load_idx = []
    sgen_idx = []
    base_load = rng.uniform(0.0018, 0.0065, size=len(xy)).astype(np.float32)
    q_ratio = rng.uniform(0.28, 0.42, size=len(xy)).astype(np.float32)
    pv_nodes = set(rng.choice(np.arange(len(xy)), size=max(4, len(xy) // 5), replace=False).tolist())

    for i, bus in enumerate(buses):
        if i == source:
            base = 0.002
        else:
            base = float(base_load[i])
        load_idx.append(pp.create_load(net, bus=bus, p_mw=base, q_mvar=base * float(q_ratio[i]), name=f"load_{i:03d}"))
        if i in pv_nodes:
            sgen_idx.append(pp.create_sgen(net, bus=bus, p_mw=float(rng.uniform(0.0005, 0.005)), q_mvar=0.0, name=f"pv_{i:03d}"))
    return net, np.asarray(load_idx), np.asarray(sgen_idx), source, base_load, q_ratio


def simulate(net, load_idx, sgen_idx, base_load, q_ratio, timesteps: int, rng: np.random.Generator):
    n = len(net.bus)
    t = np.arange(timesteps, dtype=np.float32)
    daily = 0.72 + 0.28 * np.sin(2.0 * np.pi * (t - 7.0) / 24.0) ** 2
    slow = 1.0 + 0.12 * np.sin(2.0 * np.pi * t / (24.0 * 7.0))
    phases = rng.uniform(0.0, 2.0 * np.pi, size=n).astype(np.float32)
    amps = rng.uniform(0.06, 0.18, size=n).astype(np.float32)

    voltage = np.zeros((timesteps, n), dtype=np.float32)
    va_degree = np.zeros((timesteps, n), dtype=np.float32)
    p_load = np.zeros((timesteps, n), dtype=np.float32)
    q_load = np.zeros((timesteps, n), dtype=np.float32)
    p_sgen = np.zeros((timesteps, n), dtype=np.float32)
    q_sgen = np.zeros((timesteps, n), dtype=np.float32)
    converged = np.zeros(timesteps, dtype=bool)

    sgen_buses = net.sgen["bus"].to_numpy(dtype=int) if len(net.sgen) else np.asarray([], dtype=int)
    for step in range(timesteps):
        node_factor = 1.0 + amps * np.sin(2.0 * np.pi * step / 24.0 + phases)
        p = np.clip(base_load * daily[step] * slow[step] * node_factor + rng.normal(0.0, 0.00035, n), 0.0002, None)
        q = p * q_ratio
        net.load.loc[load_idx, "p_mw"] = p
        net.load.loc[load_idx, "q_mvar"] = q

        if len(net.sgen):
            solar = max(0.0, np.sin(np.pi * ((step % 24) - 6) / 12.0))
            pv = np.clip(net.sgen["p_mw"].to_numpy(dtype=np.float32) * (0.15 + 0.95 * solar), 0.0, None)
            net.sgen.loc[sgen_idx, "p_mw"] = pv

        try:
            pp.runpp(net, calculate_voltage_angles=False, init="auto", numba=False)
            converged[step] = bool(net.converged)
        except Exception:
            converged[step] = False

        if converged[step]:
            voltage[step] = net.res_bus["vm_pu"].to_numpy(dtype=np.float32)
            va_degree[step] = net.res_bus["va_degree"].to_numpy(dtype=np.float32)
        elif step > 0:
            voltage[step] = voltage[step - 1]
            va_degree[step] = va_degree[step - 1]
        else:
            voltage[step] = 1.0

        p_load[step] = p
        q_load[step] = q
        if len(net.sgen):
            np.add.at(p_sgen[step], sgen_buses, net.sgen["p_mw"].to_numpy(dtype=np.float32))
    return {
        "voltage_pu": voltage,
        "va_degree": va_degree,
        "p_load_mw": p_load,
        "q_load_mvar": q_load,
        "p_sgen_mw": p_sgen,
        "q_sgen_mvar": q_sgen,
        "net_p_mw": p_load - p_sgen,
        "net_q_mvar": q_load - q_sgen,
        "powerflow_converged": converged,
    }


def make_splits(timesteps: int):
    train_end = int(0.7 * timesteps)
    val_end = int(0.85 * timesteps)
    return {"train": {"start": 0, "end": train_end}, "val": {"start": train_end, "end": val_end}, "test": {"start": val_end, "end": timesteps}}


def generate_one(name: str, cfg: dict, args: argparse.Namespace) -> None:
    rng = np.random.default_rng(int(cfg["seed"]))
    out_dir = PROJECT_ROOT / args.out_root / name
    out_dir.mkdir(parents=True, exist_ok=True)
    xy, labels = sample_district_positions(int(cfg["num_nodes"]), int(cfg["districts"]), rng)
    edges = build_water_like_electric_edges(
        xy,
        labels,
        rng,
        loops_per_district=int(cfg["loops_per_district"]),
        bridge_edges=int(cfg["bridge_edges"]),
        extra_cross_links=int(cfg["extra_cross_links"]),
    )
    initial_edges = build_knn_edges(xy, args.initial_knn)
    net, load_idx, sgen_idx, source, base_load, q_ratio = create_power_net(xy, edges, rng)
    series = simulate(net, load_idx, sgen_idx, base_load, q_ratio, args.timesteps, rng)

    np.savez_compressed(
        out_dir / "data.npz",
        pressure=series["voltage_pu"],
        demand=series["net_p_mw"],
        node_xy=xy,
        edge_index=to_edge_index(edges, bidirectional=True),
        initial_edge_index=to_edge_index(initial_edges, bidirectional=True),
        time_s=np.arange(args.timesteps, dtype=np.int64) * 3600,
        block_labels=labels,
        voltage_pu=series["voltage_pu"],
        va_degree=series["va_degree"],
        p_load_mw=series["p_load_mw"],
        q_load_mvar=series["q_load_mvar"],
        p_sgen_mw=series["p_sgen_mw"],
        q_sgen_mvar=series["q_sgen_mvar"],
        net_p_mw=series["net_p_mw"],
        net_q_mvar=series["net_q_mvar"],
        powerflow_converged=series["powerflow_converged"],
    )

    meta = {
        "name": "synthetic_electric",
        "dataset_id": name,
        "num_nodes": int(cfg["num_nodes"]),
        "num_gt_undirected_edges": int(len(edges)),
        "num_initial_undirected_edges": int(len(initial_edges)),
        "node_ids": [f"EB{i:03d}" for i in range(int(cfg["num_nodes"]))],
        "splits": make_splits(args.timesteps),
        "compatibility_mapping": {"pressure": "voltage_pu", "demand": "net_p_mw"},
        "allowed_for_training": ["node_xy", "voltage_pu / pressure", "net_p_mw / demand", "p_load_mw", "q_load_mvar", "p_sgen_mw", "q_sgen_mvar", "net_q_mvar"],
        "posthoc_only": ["edge_index", "pandapower line connectivity", "line impedances", "line lengths", "number of ground-truth edges"],
        "generator": {**cfg, "source": "new synthetic pandapower electric grid", "timesteps": int(args.timesteps), "initial_knn": int(args.initial_knn), "source_node": int(source), "converged_steps": int(series["powerflow_converged"].sum())},
    }
    (out_dir / "meta.json").write_text(json.dumps(meta, indent=2), encoding="utf-8")
    print(f"[OK] {name}: nodes={cfg['num_nodes']} gt_edges={len(edges)} initial_edges={len(initial_edges)} converged={int(series['powerflow_converged'].sum())}/{args.timesteps}")


def parse_args() -> argparse.Namespace:
    parser = argparse.ArgumentParser(description="Generate new synthetic electric pandapower benchmarks.")
    parser.add_argument("--out_root", type=Path, default=Path("data/synthetic"))
    parser.add_argument("--preset", choices=list(PRESETS) + ["all"], default="all")
    parser.add_argument("--timesteps", type=int, default=720)
    parser.add_argument("--initial_knn", type=int, default=3)
    return parser.parse_args()


def main() -> None:
    args = parse_args()
    selected = PRESETS if args.preset == "all" else {args.preset: PRESETS[args.preset]}
    for name, cfg in selected.items():
        generate_one(name, cfg, args)


if __name__ == "__main__":
    main()
